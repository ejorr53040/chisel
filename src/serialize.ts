import type { Block, Board, Lang } from "./board";

export interface Warning {
  blockId?: string;
  edgeId?: string;
  message: string;
}

// Output order never depends on array order or positions, so the same board always gives the same text.
const KIND_ORDER: Block["kind"][] = ["function", "module"];

export function serialize(board: Board, _lang?: Lang): { arch: string; warnings: Warning[] } {
  const children = new Map<string | undefined, Block[]>();
  for (const b of board.blocks) children.set(b.parentId, [...(children.get(b.parentId) ?? []), b]);
  const sorted = (parent?: string) =>
    (children.get(parent) ?? []).sort(
      (a, b) =>
        KIND_ORDER.indexOf(a.kind) - KIND_ORDER.indexOf(b.kind) ||
        a.name.localeCompare(b.name) ||
        a.id.localeCompare(b.id),
    );

  const render = (b: Block, indent: string): string[] => {
    const out: string[] = [];
    if (b.kind === "module") {
      out.push(`${indent}module ${b.name}  @id ${b.id}`);
    } else {
      out.push(`${indent}fn ${b.name}${b.signature || "()"}  @id ${b.id}`);
      out.push(`${indent}  intent: ${b.intent}`);
      const steps = b.steps.map((s) => s.trim()).filter(Boolean);
      if (steps.length) out.push(`${indent}  steps:`, ...steps.map((s) => `${indent}    - ${s}`));
    }
    for (const c of sorted(b.id)) out.push(...render(c, indent + "  "));
    return out;
  };

  const top = sorted(undefined).map((b) => render(b, "").join("\n"));
  const header = `# architecture: ${board.name}\n# generated by scaffold; edit the board, not this file\n\n`;
  return { arch: header + top.join("\n\n") + "\n", warnings: [] };
}
