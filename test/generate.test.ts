import { describe, expect, it } from "vitest";
import { existsSync, mkdtempSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import { generate, isRunDir, type Runner, type Verifier } from "../src/generate";

const ARCH = "# architecture: demo\n# generated by chisel; edit the board, not this file\n\nfn main()  @id f_main\n  intent: Prints hello.\n";
const tmp = () => mkdtempSync(join(tmpdir(), "chisel-gen-"));
const passes: Verifier = async () => [];

// Stands in for the agent: writes a project and the result file the prompt asks for.
const fakeAgent =
  (result: object | null, files: Record<string, string> = { "demo/main.py": "print('hello')\n" }, exitCode = 0): Runner =>
  async ({ cwd, onProgress }) => {
    onProgress("writing demo/main.py");
    for (const [f, text] of Object.entries(files)) {
      mkdirSync(join(cwd, f, ".."), { recursive: true });
      writeFileSync(join(cwd, f), text);
    }
    if (result) writeFileSync(join(cwd, "chisel-result.json"), JSON.stringify(result));
    return { exitCode, output: exitCode ? "agent crashed: out of turns" : "done" };
  };
const succeeds = fakeAgent({ ok: true, errors: [] });
const fails = fakeAgent({ ok: false, errors: [{ message: "mypy: nope" }] });

const run = (opts: Partial<Parameters<typeof generate>[0]> = {}) =>
  generate({ arch: ARCH, lang: "python", outDir: tmp(), runner: succeeds, verify: passes, ...opts });

describe("generate", () => {
  it("runs the agent in a fresh out/<lang>/<timestamp> folder holding the architecture file", async () => {
    const outDir = tmp();
    let seen: { prompt: string; cwd: string } | undefined;
    const runner: Runner = async (job) => {
      seen = job;
      return succeeds(job);
    };

    const result = await run({ outDir, runner });

    expect(result.ok).toBe(true);
    expect(result.runDir.startsWith(join(outDir, "python") + "/")).toBe(true);
    expect(seen!.cwd).toBe(result.runDir);
    expect(readFileSync(join(result.runDir, "architecture.arch.md"), "utf8")).toBe(ARCH);
    expect(seen!.prompt).toContain("architecture.arch.md");
    expect(seen!.prompt).toContain("mypy");
    expect(seen!.prompt).toContain("chisel-result.json");
    expect(result.files).toEqual(["architecture.arch.md", "chisel-result.json", "demo/main.py"]);
    expect(result.errors).toEqual([]);
  });

  it("forwards the agent's progress", async () => {
    const lines: string[] = [];
    await run({ onProgress: (l) => lines.push(l) });
    expect(lines).toContain("writing demo/main.py");
  });

  it("keeps only the five newest runs per language", async () => {
    const outDir = tmp();
    const runs: string[] = [];
    for (let i = 0; i < 6; i++) runs.push((await run({ outDir })).runDir);

    expect(new Set(runs).size).toBe(6);
    expect(existsSync(runs[0])).toBe(false);
    expect(readdirSync(join(outDir, "python")).length).toBe(5);
    for (const r of runs.slice(1)) expect(existsSync(r)).toBe(true);
  });

  it("never prunes the newest verified run, however many failed runs follow it", async () => {
    const outDir = tmp();
    const good = (await run({ outDir })).runDir;
    const bad: string[] = [];
    for (let i = 0; i < 6; i++) bad.push((await run({ outDir, runner: fails })).runDir);

    expect(existsSync(good)).toBe(true);
    expect(existsSync(bad[0])).toBe(false);
    expect(readdirSync(join(outDir, "python")).length).toBe(6);
  });

  it("reports the agent's verification errors", async () => {
    const result = await run({ runner: fakeAgent({ ok: false, errors: [{ blockId: "f_main", message: "mypy: main returns str, expected None" }] }) });
    expect(result.ok).toBe(false);
    expect(result.errors).toEqual([{ blockId: "f_main", message: "mypy: main returns str, expected None" }]);
  });

  it("re-verifies the project itself instead of trusting the agent", async () => {
    let checked = "";
    const result = await run({
      verify: async (runDir) => {
        checked = runDir;
        return [{ message: "mypy: demo/main.py:1: error" }];
      },
    });
    expect(checked).toBe(result.runDir);
    expect(result.ok).toBe(false);
    expect(result.errors).toEqual([{ message: "mypy: demo/main.py:1: error" }]);
  });

  it("fails with the agent's output when it exits non-zero", async () => {
    const result = await run({ runner: fakeAgent(null, {}, 1) });
    expect(result.ok).toBe(false);
    expect(result.errors[0].message).toMatch(/exited with code 1[\s\S]*out of turns/);
  });

  it("fails when the agent never writes its result file", async () => {
    const result = await run({ runner: fakeAgent(null) });
    expect(result.ok).toBe(false);
    expect(result.errors[0].message).toMatch(/chisel-result\.json/);
  });

  it("fails when the result file is malformed", async () => {
    const result = await run({ runner: fakeAgent({ ok: "yes" }) });
    expect(result.ok).toBe(false);
    expect(result.errors[0].message).toMatch(/malformed/);
  });

  it("stops the agent and reports a cancelled run when the signal aborts", async () => {
    const controller = new AbortController();
    const runner: Runner = ({ signal }) =>
      new Promise((resolve) => signal.addEventListener("abort", () => resolve({ exitCode: 143, output: "" })));
    const pending = run({ runner, signal: controller.signal });
    controller.abort();
    const result = await pending;
    expect(result.ok).toBe(false);
    expect(result.cancelled).toBe(true);
    expect(result.errors).toEqual([{ message: "run cancelled" }]);
  });

  it("rejects a language with no generator", async () => {
    await expect(run({ lang: "__proto__" as never })).rejects.toThrow(/no generator for __proto__/);
  });

  describe("ties errors to blocks", () => {
    const code = "# @id f_main\ndef main() -> None:\n    print('hello')\n    return 1\n";

    it("reads an @id written in the agent's error message", async () => {
      const result = await run({ runner: fakeAgent({ ok: false, errors: [{ message: "could not implement @id f_main: unclear intent" }] }) });
      expect(result.errors).toEqual([{ blockId: "f_main", message: "could not implement @id f_main: unclear intent" }]);
    });

    it("splits checker output into one error per file:line and finds each line's block by its @id comment", async () => {
      const result = await run({
        runner: fakeAgent({ ok: true, errors: [] }, { "demo/main.py": code }),
        verify: async () => [
          {
            message:
              "mypy --ignore-missing-imports . failed:\ndemo/main.py:4: error: No return value expected  [return-value]\nnotes.txt:1: error: elsewhere\nFound 2 errors in 2 files",
          },
        ],
      });
      expect(result.ok).toBe(false);
      expect(result.errors).toEqual([
        { blockId: "f_main", message: "demo/main.py:4: error: No return value expected  [return-value]" },
        { message: "notes.txt:1: error: elsewhere" },
      ]);
    });

    it("drops a blockId that is not on the board", async () => {
      const result = await run({ runner: fakeAgent({ ok: false, errors: [{ blockId: "f_ghost", message: "bad" }] }) });
      expect(result.errors).toEqual([{ message: "bad" }]);
    });

    it("leaves errors that name no block without a blockId", async () => {
      const result = await run({ runner: fakeAgent({ ok: false, errors: [{ message: "pyproject.toml is invalid" }] }) });
      expect(result.errors).toEqual([{ message: "pyproject.toml is invalid" }]);
    });
  });

  it("reads Rust's multi-line diagnostics, where the location sits on a later --> line", async () => {
    const rust = "// @id m_greet\npub mod greet {}\n\n// @id f_greeting\npub fn greeting(name: &str) -> String {\n    name\n}\n";
    const cargo = [
      "cargo check --quiet failed:",
      "warning: unused variable: `x`",
      " --> src/lib.rs:2:9",
      "  |",
      "error[E0308]: mismatched types",
      " --> src/lib.rs:6:5",
      "  |",
      "6 |     name",
      "  |     ^^^^ expected `String`, found `&str`",
      "",
      "error: could not compile `greeter` (lib) due to 1 previous error",
    ].join("\n");
    const result = await generate({
      arch: "module greet  @id m_greet\n  fn greeting(name) -> str  @id f_greeting\n",
      lang: "python",
      outDir: tmp(),
      runner: fakeAgent({ ok: true, errors: [] }, { "src/lib.rs": rust }),
      verify: async () => [{ message: cargo }],
    });
    expect(result.errors).toEqual([{ blockId: "f_greeting", message: "error[E0308]: mismatched types (src/lib.rs:6:5)" }]);
  });

  describe("attribution edge cases", () => {
    const ARCH2 = "module main  @id _main\n  fn run()  @id f-run.v2\n";
    const attributed = (errors: object[], files: Record<string, string> = {}) =>
      run({ arch: ARCH2, runner: fakeAgent({ ok: false, errors }, files) }).then((r) => r.errors);

    it("never ties an error to the synthetic default module", async () => {
      expect(await attributed([{ message: "bad @id _main" }])).toEqual([{ message: "bad @id _main" }]);
    });

    it("reads ids that contain dashes and dots, without trailing punctuation", async () => {
      expect(await attributed([{ message: "broken: @id f-run.v2." }])).toEqual([{ blockId: "f-run.v2", message: "broken: @id f-run.v2." }]);
    });

    it("falls back to the message when the agent's blockId is not on the board", async () => {
      expect(await attributed([{ blockId: "f_ghost", message: "see @id f-run.v2" }])).toEqual([{ blockId: "f-run.v2", message: "see @id f-run.v2" }]);
    });

    it("drops note lines from compiler output", async () => {
      const result = await run({
        arch: ARCH2,
        verify: async () => [{ message: "src/a.cpp:3:1: error: boom\nsrc/a.cpp:1:1: note: declared here\nmain.py:2: note: see docs" }],
      });
      expect(result.errors).toEqual([{ message: "src/a.cpp:3:1: error: boom" }]);
    });

    it("works with a relative output folder", async () => {
      const result = await run({
        arch: ARCH2,
        outDir: relative(process.cwd(), join(tmp(), "rel")),
        runner: fakeAgent({ ok: true, errors: [] }, { "src/a.py": "# @id f-run.v2\nx = 1\n" }),
        verify: async () => [{ message: "src/a.py:2: error: nope" }],
      });
      expect(result.errors).toEqual([{ blockId: "f-run.v2", message: "src/a.py:2: error: nope" }]);
    });
  });

  it("reads gcc diagnostics that use absolute paths, as CMake builds report them", async () => {
    const outDir = tmp();
    const cpp = "// @id c_cart\nclass Cart {\n  // @id f_total\n  int total() { return \"x\"; }\n};\n";
    let seenRunDir = "";
    const result = await run({
      outDir,
      arch: "module shop  @id m_shop\n  class Cart  @id c_cart\n    fn total() -> int  @id f_total\n",
      runner: async (job) => {
        seenRunDir = job.cwd;
        return fakeAgent({ ok: true, errors: [] }, { "src/shop.cpp": cpp })(job);
      },
      verify: async (runDir) => [
        {
          message: [
            "cmake --build build -j 8 failed:",
            `In file included from ${runDir}/src/main.cpp:1:`,
            `${runDir}/src/shop.cpp:4:24: error: cannot convert 'const char*' to 'int' in return`,
            "gmake[2]: *** [CMakeFiles/shop.dir/build.make:76: CMakeFiles/shop.dir/src/shop.cpp.o] Error 1",
          ].join("\n"),
        },
      ],
    });
    expect(result.errors).toEqual([{ blockId: "f_total", message: `${seenRunDir}/src/shop.cpp:4:24: error: cannot convert 'const char*' to 'int' in return` }]);
  });

  it("keeps errors that have no location alongside located ones", async () => {
    const result = await run({
      verify: async () => [
        { message: "cargo check failed:\nerror: package `x` cannot be built because it requires rustc 1.99\nerror[E0308]: mismatched types\n --> src/lib.rs:6:5\nerror: could not compile `x`" },
      ],
    });
    expect(result.errors).toEqual([
      { message: "error: package `x` cannot be built because it requires rustc 1.99" },
      { message: "error[E0308]: mismatched types (src/lib.rs:6:5)" },
    ]);
  });

  it("clears build output from older runs but keeps the newest run's", async () => {
    const outDir = tmp();
    const withTarget = fakeAgent({ ok: true, errors: [] }, { "Cargo.toml": "", "target/debug/big.bin": "x", "src/lib.rs": "" });
    const first = (await run({ outDir, runner: withTarget })).runDir;
    const second = (await run({ outDir, runner: withTarget })).runDir;
    expect(existsSync(join(first, "target"))).toBe(false);
    expect(existsSync(join(first, "src/lib.rs"))).toBe(true);
    expect(existsSync(join(second, "target/debug/big.bin"))).toBe(true);
  });

  it("recognises its own run folders and nothing else", async () => {
    const result = await run();
    expect(isRunDir(result.runDir)).toBe(true);
    expect(isRunDir(join(result.runDir, ".."))).toBe(false);
    expect(isRunDir(tmp())).toBe(false);
    expect(isRunDir("/definitely/not/here")).toBe(false);
  });

  it("only clears build output a build system made: a package named build keeps its source", async () => {
    const outDir = tmp();
    const py = fakeAgent({ ok: true, errors: [] }, { "build/__init__.py": "x = 1\n", "pyproject.toml": "" });
    const first = (await run({ outDir, runner: py })).runDir;
    await run({ outDir, runner: py });
    expect(existsSync(join(first, "build/__init__.py"))).toBe(true);
    const files = (await run({ outDir, runner: py })).files;
    expect(files).toContain("build/__init__.py");
  });

  it("keeps gcc's error lines but not its template backtrace lines, and keeps linker errors", async () => {
    const result = await run({
      verify: async () => [
        {
          message: [
            "src/a.hpp: In instantiation of 'T f() [with T = int]':",
            "src/a.cpp:9:12:   required from here",
            "src/a.hpp:5:7: error: no match for 'operator+'",
            "/usr/bin/ld: /tmp/ccA1b2.o: in function `main':",
            "a.cpp:(.text+0x5): undefined reference to `foo()'",
            "a.cpp:(.text.startup+0x9): undefined reference to `bar()'",
            "collect2: error: ld returned 1 exit status",
          ].join("\n"),
        },
      ],
    });
    expect(result.errors.map((e) => e.message)).toEqual([
      "src/a.hpp:5:7: error: no match for 'operator+'",
      "a.cpp:(.text+0x5): undefined reference to `foo()'",
      "a.cpp:(.text.startup+0x9): undefined reference to `bar()'",
    ]);
  });

  it("reads lld's undefined-symbol errors", async () => {
    const result = await run({ verify: async () => [{ message: "src/a.cpp:1:1: error: x\nld.lld: error: undefined symbol: foo()\n>>> referenced by a.cpp" }] });
    expect(result.errors.map((e) => e.message)).toEqual(["src/a.cpp:1:1: error: x", "ld.lld: error: undefined symbol: foo()"]);
  });

  it("cancels during the re-check too", async () => {
    const controller = new AbortController();
    const verify: Verifier = (_dir, _lang, signal) =>
      new Promise((resolve) => (signal.aborted ? resolve([{ message: "killed" }]) : signal.addEventListener("abort", () => resolve([{ message: "killed" }]))));
    const pending = run({ verify, signal: controller.signal, onProgress: (l) => l === "re-checking the project" && controller.abort() });
    const result = await pending;
    expect(result.cancelled).toBe(true);
    expect(result.errors).toEqual([{ message: "run cancelled" }]);
  });
});

