import { describe, expect, it } from "vitest";
import { existsSync, mkdtempSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { generate, type Runner } from "../src/generate";

const ARCH = "# architecture: demo\n# generated by scaffold; edit the board, not this file\n\nfn main()  @id f_main\n  intent: Prints hello.\n";
const tmp = () => mkdtempSync(join(tmpdir(), "scaffold-gen-"));

// Stands in for the agent: writes a project and the result file the prompt asks for.
const fakeAgent =
  (result: object | null, files: Record<string, string> = { "demo/main.py": "print('hello')\n" }, exitCode = 0): Runner =>
  async ({ cwd, onProgress }) => {
    onProgress("writing demo/main.py");
    for (const [f, text] of Object.entries(files)) {
      mkdirSync(join(cwd, f, ".."), { recursive: true });
      writeFileSync(join(cwd, f), text);
    }
    if (result) writeFileSync(join(cwd, "scaffold-result.json"), JSON.stringify(result));
    return { exitCode, output: exitCode ? "agent crashed: out of turns" : "done" };
  };

describe("generate", () => {
  it("runs the agent in a fresh out/<lang>/<timestamp> folder holding the architecture file", async () => {
    const outDir = tmp();
    let seen: { prompt: string; cwd: string } | undefined;
    const runner: Runner = async (job) => {
      seen = job;
      return fakeAgent({ ok: true, errors: [] })(job);
    };

    const result = await generate({ arch: ARCH, lang: "python", outDir, runner });

    expect(result.ok).toBe(true);
    expect(result.runDir.startsWith(join(outDir, "python") + "/")).toBe(true);
    expect(seen!.cwd).toBe(result.runDir);
    expect(readFileSync(join(result.runDir, "architecture.arch.md"), "utf8")).toBe(ARCH);
    expect(seen!.prompt).toContain("architecture.arch.md");
    expect(seen!.prompt).toContain("mypy");
    expect(seen!.prompt).toContain("scaffold-result.json");
    expect(result.files).toEqual(["architecture.arch.md", "demo/main.py", "scaffold-result.json"]);
    expect(result.errors).toEqual([]);
  });

  it("forwards the agent's progress", async () => {
    const lines: string[] = [];
    await generate({ arch: ARCH, lang: "python", outDir: tmp(), runner: fakeAgent({ ok: true, errors: [] }), onProgress: (l) => lines.push(l) });
    expect(lines).toContain("writing demo/main.py");
  });

  it("keeps only the five newest runs per language", async () => {
    const outDir = tmp();
    const runs: string[] = [];
    for (let i = 0; i < 6; i++)
      runs.push((await generate({ arch: ARCH, lang: "python", outDir, runner: fakeAgent({ ok: true, errors: [] }) })).runDir);

    expect(new Set(runs).size).toBe(6);
    expect(existsSync(runs[0])).toBe(false);
    expect(readdirSync(join(outDir, "python")).length).toBe(5);
    for (const r of runs.slice(1)) expect(existsSync(r)).toBe(true);
  });

  it("reports the agent's verification errors", async () => {
    const result = await generate({
      arch: ARCH,
      lang: "python",
      outDir: tmp(),
      runner: fakeAgent({ ok: false, errors: [{ blockId: "f_main", message: "mypy: main returns str, expected None" }] }),
    });
    expect(result.ok).toBe(false);
    expect(result.errors).toEqual([{ blockId: "f_main", message: "mypy: main returns str, expected None" }]);
  });

  it("fails with the agent's output when it exits non-zero", async () => {
    const result = await generate({ arch: ARCH, lang: "python", outDir: tmp(), runner: fakeAgent(null, {}, 1) });
    expect(result.ok).toBe(false);
    expect(result.errors[0].message).toMatch(/exited with code 1[\s\S]*out of turns/);
  });

  it("fails when the agent never writes its result file", async () => {
    const result = await generate({ arch: ARCH, lang: "python", outDir: tmp(), runner: fakeAgent(null) });
    expect(result.ok).toBe(false);
    expect(result.errors[0].message).toMatch(/scaffold-result\.json/);
  });

  it("fails when the result file is malformed", async () => {
    const result = await generate({ arch: ARCH, lang: "python", outDir: tmp(), runner: fakeAgent({ ok: "yes" }) });
    expect(result.ok).toBe(false);
    expect(result.errors[0].message).toMatch(/malformed/);
  });
});
