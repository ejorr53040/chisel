import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import type { Board } from "../src/board";
import { serialize } from "../src/serialize";

const fixture = (name: string): Board =>
  JSON.parse(readFileSync(new URL(`fixtures/${name}.scaffold.json`, import.meta.url), "utf8"));
const golden = (name: string) =>
  readFileSync(new URL(`fixtures/${name}.arch.md`, import.meta.url), "utf8");

describe("serialize", () => {
  it.each(["single-function", "module-with-functions", "nested-modules", "all-kinds", "edges"])("renders %s to its golden architecture file", (name) => {
    expect(serialize(fixture(name)).arch).toBe(golden(name));
  });
});

// Seeded so a failure reproduces.
function shuffle<T>(items: T[], seed: number): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    seed = (seed * 1103515245 + 12345) % 2 ** 31;
    const j = seed % (i + 1);
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

describe("serialize is deterministic", () => {
  it.each([1, 2, 3, 4, 5, 6, 7, 8])("ignores block array order and positions (seed %i)", (seed) => {
    const board = fixture("nested-modules");
    const reshuffled: Board = {
      ...board,
      blocks: shuffle(board.blocks, seed).map((b, i) => ({ ...b, position: { x: i * 37, y: -i * 11 } })),
    };
    expect(serialize(reshuffled).arch).toBe(golden("nested-modules"));
  });

  it("ignores edge array order", () => {
    const board = fixture("edges");
    for (const seed of [1, 2, 3, 4]) expect(serialize({ ...board, edges: shuffle(board.edges, seed) }).arch).toBe(golden("edges"));
  });

  it("orders sibling names by code point, independent of locale", () => {
    const board: Board = {
      version: 1,
      name: "x",
      edges: [],
      blocks: ["b", "B", "a", "é"].map((name) => ({ id: `m_${name}`, kind: "module", name, position: { x: 0, y: 0 } })),
    };
    const order = serialize(board).arch.match(/^module (\S+)/gm);
    expect(order).toEqual(["module B", "module a", "module b", "module é"]);
  });
});

describe("serialize keeps the file line-oriented", () => {
  it("renders an empty board as just the header, ending in one newline", () => {
    expect(serialize({ version: 1, name: "x", blocks: [], edges: [] }).arch).toBe(
      "# architecture: x\n# generated by scaffold; edit the board, not this file\n",
    );
  });

  it("folds newlines in names and intents onto one line", () => {
    const board = fixture("single-function");
    Object.assign(board.blocks[0], { name: "log\nin", intent: "Checks the\n  password.\n" });
    expect(serialize(board).arch).toContain("  fn log in(email, password) -> User  @id f_login\n    intent: Checks the password.\n");
  });

  it.each([
    ["", "()"],
    ["(a, b) -> C", "(a, b) -> C"],
    ["email, password -> User", "(email, password) -> User"],
    ["token", "(token)"],
    ["-> Config", "() -> Config"],
  ])("wraps the loose signature %j as %j", (signature, rendered) => {
    const board = fixture("single-function");
    Object.assign(board.blocks[0], { signature });
    expect(serialize(board).arch).toContain(`fn login${rendered}  @id f_login`);
  });
});

describe("serialize skips blank steps", () => {
  it("drops empty and whitespace-only steps, and the steps line when none remain", () => {
    const board = fixture("single-function");
    const fn = board.blocks[0] as Extract<Board["blocks"][number], { kind: "function" }>;
    fn.steps = ["look up the user by email", "", "   "];
    expect(serialize(board).arch).toContain("    steps:\n      - look up the user by email\n");
    expect(serialize(board).arch).not.toContain("- \n");
    fn.steps = ["", " "];
    expect(serialize(board).arch).not.toContain("steps:");
  });
});

describe("serialize's default module", () => {
  it("puts unparented blocks into the user's own top-level main module when there is one", () => {
    const board: Board = {
      version: 1,
      name: "x",
      edges: [],
      blocks: [
        { id: "m_main", kind: "module", name: "main", position: { x: 0, y: 0 } },
        { id: "s_db", kind: "service", name: "db", position: { x: 0, y: 0 }, description: "" },
      ],
    };
    expect(serialize(board).arch).toBe(
      "# architecture: x\n# generated by scaffold; edit the board, not this file\n\nmodule main  @id m_main\n  service db  @id s_db\n",
    );
  });
});

describe("serialize's default module is deterministic", () => {
  it("picks the top-level main module with the smallest id when there are two", () => {
    const blocks: Board["blocks"] = [
      { id: "m_b", kind: "module", name: "main", position: { x: 0, y: 0 } },
      { id: "m_a", kind: "module", name: "main", position: { x: 0, y: 0 } },
      { id: "s_db", kind: "service", name: "db", position: { x: 0, y: 0 }, description: "" },
    ];
    const outputs = [1, 2, 3, 4].map((seed) => serialize({ version: 1, name: "x", edges: [], blocks: shuffle(blocks, seed) }).arch);
    expect(new Set(outputs).size).toBe(1);
    expect(outputs[0]).toContain("module main  @id m_a\n  service db  @id s_db\n");
  });
});
